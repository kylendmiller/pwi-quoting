// Calibration vs PWI's sold jobs. `npm run calibrate` rewrites docs/calibration.md from the current
// engine; `npm test` fails if any job's gap moves more than 2 points from that table, so rule changes
// can't silently drift the prices. Re-run `npm run calibrate` on purpose after a tuning change.
import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { runAll, table, readTable, type CalRow } from './calibration/harness';
import { CASES, SKIPPED } from './calibration/cases';

const DOC = 'docs/calibration.md', BEFORE = 'docs/calibration_before.json';

function summary(rows: CalRow[]) {
  const by = new Map<string, CalRow[]>();
  for (const r of rows) if (!r.outlier) by.set(r.product, [...(by.get(r.product) ?? []), r]);
  return [...by].map(([p, rs]) => {
    const abs = rs.map(r => Math.abs(r.gapPct));
    return `| ${p} | ${rs.length} | ${(rs.reduce((a, r) => a + r.gapPct, 0) / rs.length).toFixed(1)} | ${(abs.reduce((a, b) => a + b, 0) / abs.length).toFixed(1)} | ${Math.max(...abs).toFixed(1)} | ${rs.filter(r => Math.abs(r.gapPct) <= 3).length}/${rs.length} |`;
  }).join('\n');
}

describe('calibration vs sold jobs', () => {
  const rows = runAll();
  it('every case builds without blockers about missing parts', () => {
    for (const r of rows) expect(r.blockers.filter(b => /not found|not in/.test(b)), r.job).toEqual([]);
  });
  it('every fixture is either calibrated or listed as skipped', () => {
    const files = readFileSync('fixtures/index.json', 'utf8');
    const jobs: string[] = JSON.parse(files).map((x: any) => x.job);
    const known = new Set([...CASES.map(c => c.job), ...SKIPPED.map(s => s[0])]);
    expect(jobs.filter(j => !known.has(j))).toEqual([]);
  });
  if (process.env.CALIBRATE_WRITE) {
    it('writes docs/calibration.md', () => {
      const before: Record<string, number> = existsSync(BEFORE) ? JSON.parse(readFileSync(BEFORE, 'utf8')) : Object.fromEntries(rows.map(r => [r.job, +r.gapPct.toFixed(1)]));
      if (!existsSync(BEFORE)) writeFileSync(BEFORE, JSON.stringify(before, null, 1) + '\n');
      const md = `# Calibration vs sold jobs

Generated by \`npm run calibrate\` (tests/calibration.test.ts). Do not edit by hand.

- **Gap %** = built base ÷ sold base at today's prices − 1. Base price = Main Summary D31 (materials, shop labor, PM, CAD, P.E., 1%) — install, travel, equipment and freight are not in it.
- **Sold base @ today's prices**: the sold job's structural and plate steel re-priced at the \`steel_cost\` seed (${'`'}src/engine/rules/steel_cost.default.json${'`'}), and its vendor items, standard parts and standard paint booth runs re-priced at today's price lists (rows not in today's lists stay as sold); markups and the 1% included. Labor rates and markups are left as sold.
- **Before %**: gap when the harness was first run (before overnight tuning), from \`${BEFORE}\`.
- **(outlier)** jobs are priced but kept out of the product averages used for tuning (reason in the notes below).
- \`npm test\` fails if any job's Gap % moves more than 2 points from this table.

${table(rows, before)}

## By product (outliers excluded)

| Product | Jobs | Mean gap % | Mean abs gap % | Worst abs % | Within ±3% |
|---|---:|---:|---:|---:|---:|
${summary(rows)}

## Notes per job

${rows.map(r => `- **${r.job}**${r.note ? ` — ${r.note}` : ''}${r.outlier ? ` *Outlier: ${r.outlier}*` : ''}`).join('\n')}

## Sold jobs not calibrated

${SKIPPED.map(([j, w]) => `- ${j} — ${w}`).join('\n')}
`;
      writeFileSync(DOC, md);
      console.log(table(rows, before));
    });
  } else {
    it('no job drifts more than 2 points from docs/calibration.md', () => {
      const t = readTable(readFileSync(DOC, 'utf8'));
      const drift = rows.filter(r => t[r.job] == null || Math.abs(r.gapPct - t[r.job]) > 2).map(r => `${r.job}: table ${t[r.job]} now ${r.gapPct.toFixed(1)}`);
      expect(drift, 'run `npm run calibrate` if the change is intended').toEqual([]);
    });
  }
});
